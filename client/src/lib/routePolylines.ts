// In-memory cache for any dynamically requested routes
const dynamicRouteCache = new Map<string, [number, number][]>();

/**
 * Returns structured road polyline coordinates for a dependency edge.
 * Always guarantees starting at source [lng, lat] and ending at target [lng, lat].
 */
export function getEdgeRouteCoordinates(
  edgeId: string,
  source: { lng: number; lat: number },
  target: { lng: number; lat: number }
): [number, number][] {
  const cached = STATIC_ROAD_ROUTES[edgeId];
  if (cached && cached.coordinates.length >= 2) {
    const coords = [...cached.coordinates];
    coords[0] = [source.lng, source.lat];
    coords[coords.length - 1] = [target.lng, target.lat];
    return coords;
  }

  const cacheKey = `${source.lng},${source.lat}->${target.lng},${target.lat}`;
  if (dynamicRouteCache.has(cacheKey)) {
    return dynamicRouteCache.get(cacheKey)!;
  }

  // Default fallback: direct line between coordinates
  return [
    [source.lng, source.lat],
    [target.lng, target.lat],
  ];
}

/**
 * Returns route metadata (distance, transit time, corridor name)
 */
export function getRouteMetadata(edgeId: string): RouteGeometryData | null {
  return STATIC_ROAD_ROUTES[edgeId] ?? null;
}

/**
 * Asynchronously fetches street-accurate road geometry from OSRM routing engine
 * for dynamic point pairs with automatic fallback.
 */
export async function fetchDynamicRouteGeometry(
  sourceLng: number,
  sourceLat: number,
  targetLng: number,
  targetLat: number
): Promise<[number, number][]> {
  const cacheKey = `${sourceLng},${sourceLat}->${targetLng},${targetLat}`;
  if (dynamicRouteCache.has(cacheKey)) {
    return dynamicRouteCache.get(cacheKey)!;
  }

  try {
    const url = `https://router.project-osrm.org/route/v1/driving/${sourceLng},${sourceLat};${targetLng},${targetLat}?overview=full&geometries=geojson`;
    const res = await fetch(url);
    if (!res.ok) throw new Error(`Routing API status ${res.status}`);
    const data = await res.json();
    if (data.routes && data.routes[0]?.geometry?.coordinates) {
      const roadCoords: [number, number][] = [
        [sourceLng, sourceLat],
        ...data.routes[0].geometry.coordinates,
        [targetLng, targetLat],
      ];
      dynamicRouteCache.set(cacheKey, roadCoords);
      return roadCoords;
    }
  } catch (err) {
    console.warn('[Routing] OSRM route fetch failed, using fallback:', err);
  }

  const fallback: [number, number][] = [
    [sourceLng, sourceLat],
    [targetLng, targetLat],
  ];
  return fallback;
}
